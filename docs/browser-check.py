from pathlib import Path
from playwright.sync_api import sync_playwright
import json

out=Path('docs/screenshots');out.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='msedge')
    page=browser.new_page(viewport={'width':1440,'height':1050},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('dialog',lambda dialog:dialog.accept())
    page.goto('http://localhost:5173',wait_until='networkidle')
    print(page.locator('h1').inner_text())
    page.screenshot(path=str(out/'desktop.png'),full_page=True,animations="disabled")
    page.locator('a[href="#/bank/b1"]').first.click()
    page.get_by_role('button',name='01 顺序练习').click()
    page.get_by_label('反复阅读同一段内容').check()
    page.reload(wait_until='networkidle')
    assert page.get_by_label('反复阅读同一段内容').is_checked()
    page.get_by_role('button',name='提交答案').click()
    assert page.get_by_text('继续加油，再理解一次').is_visible()
    page.get_by_role('button',name='收藏题目',exact=True).click()
    page.get_by_role('button',name='下一题').click()
    page.get_by_label('资源未找到').check()
    page.get_by_role('button',name='提交答案').click()
    page.get_by_role('button',name='下一题').click()
    for name in ['数组','链表','栈']:page.get_by_label(name).check()
    page.get_by_role('button',name='提交答案').click()
    assert page.get_by_text('✓ 回答正确').is_visible()
    page.screenshot(path=str(out/'practice.png'),full_page=True,animations="disabled")
    page.get_by_role('button',name='结束练习').click()
    page.locator('a[href="#/mistakes"]').first.click()
    assert page.get_by_role('heading',name='以下哪一种学习方式更有助于长期记忆？').is_visible()
    page.get_by_role('button',name='标记掌握').click()
    assert page.get_by_text('目前没有待复习的错题').is_visible()
    page.goto('http://localhost:5173/#/bank/b1')
    page.get_by_role('button',name='04 模拟考试').click()
    page.get_by_role('button',name='交卷并查看成绩').click()
    assert page.get_by_text('本次练习已结束 · 正确 0 / 5 道').is_visible()
    page.goto('http://localhost:5173/#/banks')
    page.get_by_role('button',name='导入题库').click()
    payload=[{'type':'single','stem':'测试导入','options':['一','二'],'answer':['二'],'difficulty':1}]
    page.locator('#import-file').set_input_files({'name':'test.json','mimeType':'application/json','buffer':json.dumps(payload).encode()})
    page.get_by_role('button',name='确认导入').click()
    assert page.get_by_role('heading',name='测试导入').is_visible()
    page.goto('http://localhost:5173/#/stats')
    assert page.get_by_role('heading',name='学习统计').is_visible()
    assert len(json.loads(page.evaluate('localStorage.getItem("zhixu:v1")'))['attempts'])==8
    page.set_viewport_size({'width':390,'height':844})
    page.goto('http://localhost:5173/#/home')
    page.screenshot(path=str(out/'mobile.png'),full_page=True,animations="disabled")
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    assert not errors,errors
    print('PASS: draft recovery, single/multiple scoring, favorites, mistakes, exam, import, statistics, mobile overflow; no page errors')
    browser.close()
